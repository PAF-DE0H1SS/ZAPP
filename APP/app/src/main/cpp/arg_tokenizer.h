// Разбор пользовательской аргументной строки и подстановка `$HOSTS`.
//
// Чистый C++ без JNI, семантика -- строка в строку с ArgTokenizer.kt:
// обе стороны обязаны отдать одинаковый список, иначе путь через
// expect/actual даст разный результат на устройстве и на десктопе.
#pragma once

#include <string>
#include <vector>

// Пользовательская строка на отдельные аргументы; пустые куски прочь.
// Кавычки (обе кавычки) работают и посреди токена, незакрытая кавычка
// не ошибка, эскапов нет -- обратный слэш обычный символ, как в Kotlin.
std::vector<std::string> TokenizeArgs(const std::string& input);

// Подстановка `$HOSTS` активным списком доменов: отдельный токен
// разворачивается в отдельные аргументы, вплетённый в другой токен --
// в строку через пробел одним аргументом; пустой список гасит токен.
std::vector<std::string> ExpandHosts(const std::vector<std::string>& tokens,
                                     const std::vector<std::string>& hosts);
