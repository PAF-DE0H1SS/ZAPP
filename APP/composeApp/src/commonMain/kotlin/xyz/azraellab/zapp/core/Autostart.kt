package xyz.azraellab.zapp.core

/**
 * Автозапуск: регистрация приложения на вход в систему.
 *
 * Регистрация и есть состояние: Run-ключ Windows, файл в автостарте
 * XDG на Linux, Login Items на macOS. Поэтому статус читается обратно
 * из системы, а не хранится в конфиге: переустановка или правка
 * руками не оставляют тумблер врущим.
 *
 * На Android поддержки нет ([supported] == false): старт устройства
 * делает BroadcastReceiver по флагу `bootAutostart`, а «добавить в
 * автозагрузку» у разных производителей -- личная настройка.
 */
expect object AutostartCtl {

    /** Есть ли у платформы способ зарегистрировать приложение. */
    val supported: Boolean

    /** Зарегистрировано ли приложение сейчас (по данным системы). */
    fun status(): Boolean

    /** Ставит регистрацию; false -- не удалось, ничего не записано. */
    fun enable(): Boolean

    /** Снимает регистрацию; отсутствие записи -- не ошибка. */
    fun disable(): Boolean
}
