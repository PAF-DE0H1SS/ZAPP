package xyz.azraellab.zapp.core

/**
 * Синхронизация реестра автозапуска после сохранения конфига.
 *
 * Правка настроек -- единственный момент, когда намерения меняются,
 * поэтому реестр обновляется ровно в точке записи конфига, а не
 * живёт своей жизнью и не расходится с ним.
 */
expect object BootSync {

    /** Обновляет реестр (и состояние ресивера) по свежему конфигу. */
    fun onConfigSaved(config: AppConfig)
}
