package xyz.azraellab.zapp.core

/**
 * Режим сборки: разрешено ли поднимать права через `su`.
 *
 * Android-приложение выставляет значение из `BuildConfig.ZAPP_ROOT`
 * (флавор `root` / `noroot`) в `ZappApp.onCreate` -- до Activity, до
 * первого кадра и до инициализации каких-либо движков: плитки шторки
 * поднимают процесс и без окна. На десктопе остаётся `true`: там
 * полный режим, `RootShell` и так работает от текущего пользователя.
 *
 * Когда `rootAllowed == false`, `RootShell.mode()` возвращает `Mode.NONE`
 * без единой попытки запустить `su`: noroot-сборка не должна дёргать
 * Magisk-промпты и не должна зависеть от их ответа.
 *
 * ## Единственный источник истины по флагу (E9)
 *
 * Два вопроса, которые легко перепутать, и правило, кто на какой отвечает:
 *
 * * **«Что показывать?»** -- сюда только [rootAllowed]. Любой UI-решения:
 *   строки Root/Magisk, баннеры, объяснения причин. Правило простое:
 *   `rootAllowed == false` означает, что в этой сборке про root не
 *   говорят вовсе, и никакой ответ устройства этого не меняет.
 * * **«Есть ли `su` на этом устройстве?»** -- сюда `RootShell.available()`,
 *   и только в рут-сборке: механизм выбирается под то, что реально
 *   установлено (iptables против сессии, ядерный wg против sing-box,
 *   nfqueue против релея). В норуте `available()` всегда `false`, так что
 *   условие «норут или нет su» пишется как `!rootAllowed || !available()`
 *   -- обе половины нужны: первая про сборку, вторая про устройство.
 *
 * UI не зовёт `RootShell` напрямую ни в одном файле `ui/` -- этим
 * разделением и держится разница между флаворами.
 */
object BuildMode {

    /** Разрешены ли root-команды (пробы `su`, iptables, NFQUEUE и т.п.). */
    var rootAllowed: Boolean = true
}
