package xyz.azraellab.zapp.core

/** Событие, на которое приложение отвечает коротким вибро-откликом. */
enum class HapticEvent {
    /** Успешное подключение. */
    CONNECTED,

    /** Разрыв соединения. */
    DISCONNECTED,

    /** Ошибка подключения. */
    ERROR
}

/**
 * Короткий вибро-отклик на события состояния (UX3).
 *
 * Три сигнала разной длительности: мягкий на подключении, лёгкий толчок на
 * разрыве, двойной на ошибке. Вибро звучит только на смене состояния
 * туннеля -- не на каждом кадре и не на каждом обновлении счётчиков.
 *
 * На десктопе -- пусто: тактов под рукой нет, а сообщение об ошибке и так
 * видно на экране.
 */
expect object Haptics {
    fun pulse(event: HapticEvent)
}
