package xyz.azraellab.zapp.core

/**
 * Иконка приложения, отражающая статус подключения.
 *
 * Меняется переключением activity-alias: два компонента-обёртки над
 * одной MainActivity с разными иконками, лаунчер получает
 * PACKAGE_CHANGED и подменяет значок на рабочем столе. Анимация
 * невозможна -- это подмена одной иконки на другую, и не каждый
 * лаунчер перерисовывает её мгновенно.
 *
 * Объект, а не функция состояния: вызывается из подписки на статус
 * туннеля, которой нужен только факт «подключено/нет».
 */
expect object LauncherIcon {

    /**
     * Переключает иконку: true -- «подключено» (unlock), false -- всё
     * остальное (lock). Повторный вызов с тем же значением ничего не
     * делает, чтобы не рассылать change-события лаунчеру вхолостую.
     */
    fun setConnected(connected: Boolean)
}
