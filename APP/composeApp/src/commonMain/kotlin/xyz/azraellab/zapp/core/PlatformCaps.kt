package xyz.azraellab.zapp.core

/**
 * Что умеет текущая платформа.
 *
 * Существует, чтобы разделы прятались, а не показывали заглушку. Раньше вкладка
 * GPS была на всех платформах и на десктопе вела на экран «недоступно» --
 * нажатие выглядело как поломка, хотя всё работало как задумано.
 */
interface PlatformCaps {
    /**
     * Есть ли системный способ подменить координаты.
     *
     * Имеется в виду API тест-провайдера: на Android он есть, на Windows и Linux
     * его нет, и приложение не будет делать вид, что он есть.
     */
    val gpsSpoofingSupported: Boolean

    /**
     * Можно ли установить скачанное APK обновление.
     *
     * На Android штатный установщик есть всегда; на десктопе APK не
     * устанавливается, и кнопки «Скачать/Установить» прячутся в пользу
     * открытия страницы релиза.
     */
    val apkUpdatesSupported: Boolean

    /**
     * Есть ли у системы прокси-настройки, которые приложение может
     * временно взять на себя: реестр Windows, gsettings/env
     * на Linux, networksetup на macOS. На Android прокси управляется
     * только через VPN-сессию, поэтому тумблер там не показывается.
     */
    val systemProxySupported: Boolean

    /**
     * Можно ли зарегистрировать приложение на вход в систему:
     * Run-ключ Windows, автостарт XDG на Linux, Login Items на macOS.
     * На Android тумблер остаётся флагом конфига для BroadcastReceiver,
     * и тут показывается как есть, без регистрации в системе.
     */
    val autostartSupported: Boolean

    /**
     * Приложение запущено на Android TV (или аналогичном leanback-устройстве).
     *
     * Определяется в рантайме, а не при компиляции: телефон и приставка
     * собираются из одного androidMain. На TV пульт -- единственный ввод,
     * поэтому по флагу включается крупный шрифт и обводка фокуса.
     */
    val tvMode: Boolean
}

expect fun platformCaps(): PlatformCaps
