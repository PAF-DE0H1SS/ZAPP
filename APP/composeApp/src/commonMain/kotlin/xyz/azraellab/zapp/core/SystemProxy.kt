package xyz.azraellab.zapp.core

/**
 * Системный прокси десктопа.
 *
 * Пока туннель поднят, приложение может взять на себя прокси-настройки
 * машины: браузеры и другие программы, следующие системному прокси,
 * уходят через локальные входы sing-box и получают те же маршруты и те
 * же узлы, что и весь остальной трафик. На остановке (и на старте после
 * краша) прежнее состояние возвращается по сохранённому снимку --
 * паттерн «зафиксировал -> изменил -> восстановил».
 *
 * На Android методы -- заглушка: там системный прокси не нужен, весь
 * трафик и так проходит через VPN-сессию, и настройки машины трогать
 * нечем.
 */
expect object SystemProxyCtl {
    /** Фиксирует текущее состояние системы и включает свой прокси. */
    suspend fun apply()

    /** Возвращает состояние из последнего снимка; без снимка -- тихий no-op. */
    suspend fun restore()
}

/**
 * Локальные входы, на которые сочитывается системный прокси.
 *
 * Порта отдельные от релея обхода (19050) и от tor (9050): слушателей
 * два, socks и http, потому что разные ОС указывают разные схемы --
 * Windows и GNOME понимают и socks, и http, macOS предпочитает socks,
 * а часть программ на Linux умеет только http.
 */
object ProxyPorts {
    const val SOCKS: Int = 19060
    const val HTTP: Int = 19061
}
