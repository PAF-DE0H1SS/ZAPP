package xyz.azraellab.zapp.core.daemon

/**
 * NFQUEUE-правила для демонов обхода (nfqws, goodbyedpi).
 *
 * Оба бинаря работают, только когда ядро отдаёт им пакеты: без правила
 * в mangle/OUTPUT процесс живёт, но ни одного пакета не видит -- тихо
 * бесполезен. Правило одно на обе цели: цепочка ставится, пока поднят
 * хотя бы один из демонов, и снимается, когда не осталось ни одного.
 *
 * Пакеты уходят в очередь без ожидания (`--queue-bypass`): мёртвый
 * демон -- это обычная доставка, а не чёрная дыра. Локальные назначения
 * возвращаются сразу: LAN не должен ходить через userspace ради обхода,
 * которого там нет.
 */
expect object DpiFirewall {

    /**
     * Ставит/обновляет цепочку под текущие цели.
     *
     * [tcpPorts]/[udpPorts] -- токены вида `80` или `8000:8010`; пустой
     * список tcp означает «весь tcp» (так же, как пустой `--filter-tcp`
     * у nfqws). Идемпотентно: повторный вызов перестраивает цепочку,
     * а не плодит дубли.
     */
    fun enable(tcpPorts: List<String>, udpPorts: List<String>)

    /** Снимает цепочку. Идемпотентно: нет цепочки -- нет ошибки. */
    fun disable()
}
