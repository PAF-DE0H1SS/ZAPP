package xyz.azraellab.zapp.core.daemon

/**
 * Одна мутация правил: привести строку [rule] к состоянию [add].
 */
data class Mutation(val rule: String, val add: Boolean)

/**
 * Сверка желаемого и фактического набора правил (reconcile).
 *
 * Прежняя модель «apply & pray» перезаписывала цепочку целиком и не
 * знала, что осталось после краша посреди применения. Reconcile
 * сверяет факт с желанием и двигается по одной мутации: недостающее
 * добавить, лишнее убрать. Порядок -- сначала добавления (удаления не
 * должны съесть то, что вот-вот вернётся), порядок внутри каждой
 * группы -- как в источниках, для детерминизма тестов и дебага.
 *
 * Правила цепочки обхода коммутативны между собой (каждое ловит свою
 * пару порт/uid), поэтому сверка здесь -- множественная: это честно
 * для семейства портовых правил NFQUEUE.
 */
fun reconcilePlan(desired: Collection<String>, actual: Collection<String>): List<Mutation> {
    val want = desired.toSet()
    val have = actual.toSet()
    return want.filter { it !in have }.map { Mutation(it, add = true) } +
        have.filter { it !in want }.map { Mutation(it, add = false) }
}

/**
 * Применяет план по одной мутации; возвращает те, что не прошли.
 *
 * Проваленные возвращаются списком -- их повторит следующий проход,
 * а удачные не откатываются: чужой сбой одной строки не повод
 * распускать уже работающие правила. Мутации не зависят друг от друга,
 * поэтому порядок применения не влияет на результат сверки.
 */
fun applyPlan(plan: List<Mutation>, apply: (Mutation) -> Boolean): List<Mutation> =
    plan.filterNot { apply(it) }
