package xyz.azraellab.zapp.core.dev

/**
 * Debug-сборка ли сейчас запущена.
 *
 * Вкладка «Для разработчиков» существует только в debug: релизный APK и
 * MSI не должны показывать инструменты, которыми пользователю пользоваться
 * не нужно, а заодно -- не должны содержать видимой кнопки, ведущей к
 * внутренним проверкам.
 *
 * Решение платформенное, а не флагом сборки: на Android это признак
 * FLAG_DEBUGGABLE манифеста (то, чем `assembleDebug` отличается от
 * `assembleRelease`), на десктопе -- как запущено: из каталога classes
 * (gradle run / IDE) это debug, из jar внутри jpackage-дистрибутива -- релиз.
 */
internal expect fun isDebugBuild(): Boolean
