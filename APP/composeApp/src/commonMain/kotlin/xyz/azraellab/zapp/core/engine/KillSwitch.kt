package xyz.azraellab.zapp.core.engine

/**
 * Kill switch: пока туннель поднят, весь трафик, кроме самого
 * туннеля и соединений ядра, блокируется; при остановке и после краша
 * блокировка снимается.
 *
 * Механизм у каждой платформы свой: цепочки iptables/ip6tables на Linux,
 * правила брандмауэра и перевод системного DNS внутрь туннеля на Windows,
 * штатная «чёрная дыра» VPN-сессии на Android. macOS блокировки не
 * делает и честно сообщает об этом в журнал.
 */
expect object KillSwitchCtl {

    /**
     * Ставит блокировку и возвращает true, если она встала.
     *
     * @param endpoints адреса узлов профиля -- ядро ходит к ним напрямую,
     *   мимо туннеля, поэтому их блокировать нельзя.
     * @param dns DNS-серверы конфига; пусто, когда соответствующий флаг
     *   выключен. Без них переподключение по доменному имени не резолвится.
     * @param log строки журнала: о включении, пропусках и отказах прав.
     */
    fun install(endpoints: List<String>, dns: List<String>, log: (String) -> Unit): Boolean

    /**
     * Снимает блокировку: возвращает правила сети и системный DNS
     * по снимку. Повторные вызовы и вызовы «ничего не ставилось»
     * безопасны -- на десктопе они заодно чистят остатки после краша.
     */
    fun remove(log: (String) -> Unit)
}
