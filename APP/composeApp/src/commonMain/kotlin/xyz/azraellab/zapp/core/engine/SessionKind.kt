package xyz.azraellab.zapp.core.engine

/**
 * Чья сессия сейчас поднимается или работает в туннеле.
 *
 * Туннель один на всё приложение, но поднимает его всегда кто-то один:
 * вкладка VPN, вкладка Tor или автоматика обхода на сборках без root
 * (пассивный релей). Владелец отвечает на вопрос «чей это туннель» --
 * и вкладка показывает его как свой, только когда сессия её рода.
 */
enum class SessionKind {

    /** Владелец неизвестен: сессию ещё не запрашивали. */
    NONE,

    /** Обычный VPN-коннект, поднятый вкладкой VPN. */
    VPN,

    /** Мост Tor, поднятый вкладкой Tor. */
    TOR,

    /**
     * Пассивная сессия обхода на сборках без root.
     *
     * Поднимается автоматикой обхода, а не выбором пользователя,
     * поэтому не выдаётся ни за VPN, ни за Tor: запущенный zapret не
     * должен зажигать обе вкладки сразу.
     */
    DPI
}

/**
 * Состояние туннеля глазами одной вкладки.
 *
 * Обе страницы -- VPN и Tor -- читают одно состояние общего движка, и
 * раньше рисовали его как своё: подключённый VPN выглядел подключённым
 * Tor (и наоборот), а пассивный релей обхода зажигал обе сразу. Вкладка
 * видит живую сессию только когда она её рода; чужая показывается
 * отключённой.
 *
 * [tab] -- владелец, которого ждёт вкладка; [owner] -- фактический
 * владелец сессии. Состояние ERROR не исключение: сбой остаётся
 * «своей» для вкладки, которая его вызвала, и чужой не показывается.
 */
fun TunnelState.shownFor(tab: SessionKind, owner: SessionKind): TunnelState =
    if (tab == owner) this else TunnelState.DISCONNECTED
