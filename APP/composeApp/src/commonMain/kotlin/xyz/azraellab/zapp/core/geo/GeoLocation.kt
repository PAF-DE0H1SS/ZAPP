package xyz.azraellab.zapp.core.geo

/**
 * Точка на Земле с подписями.
 *
 * Город и страна нужны не для красоты: они показываются в логе режима
 * «координаты VPN», чтобы было видно, куда именно переехала подмена.
 */
data class GeoPoint(
    val latitude: Double,
    val longitude: Double,
    val city: String = "",
    val country: String = ""
) {
    val valid: Boolean
        get() = latitude in -90.0..90.0 && longitude in -180.0..180.0
}

/**
 * Определяет, где находится адрес, по внешнему гео-сервису.
 *
 * Нужен только для режима «координаты VPN»: локальная база гео-IP в
 * приложение не кладётся -- она весит десятки мегабайт, а точность в
 * пределах города для этой задачи избыточна.
 *
 * [address] -- домен или IP шлюза. `null`, если сети нет, сервис
 * недоступен или адрес не разрешается: вызывающий сам решает, что
 * делать (показать ошибку или взять координаты вручную).
 */
expect suspend fun geolocate(address: String): GeoPoint?
