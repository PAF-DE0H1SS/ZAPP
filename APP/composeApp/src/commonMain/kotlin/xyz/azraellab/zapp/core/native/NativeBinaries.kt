package xyz.azraellab.zapp.core.native

/**
 * Нативные бинари приложения, лежащие в APK и распакованные на устройство.
 *
 * Статическая модель вместо скачивания: nfqws, goodbyedpi, wg (Amnezia),
 * box и openvpn собираются вместе с приложением для каждой поддерживаемой
 * архитектуры и лежат в assets сжатыми. При первом старте они раскладываются
 * в каталог приложения, дальше движки работают с готовыми путями.
 *
 * Распаковка разделяется на «подготовить» и «спросить»: готовность ждут
 * только те, кто реально запускает бинари (автостарт демонов), а UI стартует
 * не дожидаясь 19 МБ распаковки.
 */
expect object NativeBinaries {

    /** Что распаковывается: имя файла в assets и в каталоге приложения. */
    val tools: List<String>

    /**
     * Распаковывает бинари под текущую архитектуру.
     *
     * Идемпотентно: при уже распакованных файлах той же версии это no-op.
     * Никогда не бросает: сбой -- это не крах приложения, а честная ошибка
     * первого запуска демона, который её и покажет.
     */
    suspend fun awaitReady()

    /**
     * Путь к распакованному бинарю или null, если его нет.
     *
     * null -- обычное состояние на десктопе: там бинари ищутся в PATH,
     * а не в assets.
     */
    fun path(tool: String): String?

    /** Какие инструменты уже лежат на диске; на десктопе -- всегда пусто. */
    fun installed(): List<String>

    /** Сносит распакованные файлы и достаёт их заново из assets. */
    suspend fun reinstall()
}
