package xyz.azraellab.zapp.core.net

/**
 * Один GET-запрос наружу, общий для всех платформ.
 *
 * Отдельный expect, а не готовый клиент: общему коду нужен ровно один
 * сценарий -- «дай текст по ссылке или null», и лишние возможности здесь
 * только размывали бы границу между «что» и «как».
 *
 * null, если сети нет, сервер ответил не 2xx или ссылка битая: вызывающий
 * сам решает, что ответить пользователю -- ошибку проверки или пустоту.
 */
expect suspend fun httpGetText(url: String): String?

/**
 * Открывает ссылку в браузере по умолчанию.
 *
 * false, если открыть не удалось: показать ошибку важнее, чем сделать вид,
 * что переход случился.
 */
expect fun openUrl(url: String): Boolean
