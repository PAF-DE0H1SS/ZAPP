package xyz.azraellab.zapp.core.notify

/**
 * Действие, встроенное прямо в уведомление.
 *
 * Отказ требует не «прочитать позже», а «поправить сейчас»: кнопка
 * в шторке экономит пользователю путь «раскрыть приложение -> найти
 * вкладку -> открыть раздел». Платформа знает, как открыть то, что
 * действие описывает, общий код -- только что действие есть.
 */
enum class NotifierAction {

    /** Открыть настройки приложения. */
    OPEN_SETTINGS
}

/**
 * Системные уведомления.
 *
 * Общий код только формулирует события -- что показать, платформа решает
 * сама: Android кладёт их в шторку, на десктопе системных уведомлений
 * в общей поставке нет.
 *
 * [tag] объединяет повторы: «подмена включилась» и «подмена выключилась»
 * -- это одно место в шторке, которое обновляется, а не две строки,
 * накапливающиеся после десятка переключений.
 */
interface Notifier {

    /** Есть ли на платформе способ показать уведомление. */
    val supported: Boolean

    /**
     * Показывает уведомление.
     *
     * Вызов молча игнорируется, если разрешения на уведомления нет: событие
     * не настолько срочное, чтобы дёргать пользователя системным диалогом
     * посреди другого дела.
     *
     * [action] с непустой [actionLabel] превращает показ в heads-up:
     * уведомление с действием важно увидеть сразу, а не в следующий раз,
     * когда пользователь откроет шторку сам.
     */
    fun show(
        title: String,
        body: String,
        tag: String,
        action: NotifierAction? = null,
        actionLabel: String = ""
    )
}

expect fun createNotifier(): Notifier
