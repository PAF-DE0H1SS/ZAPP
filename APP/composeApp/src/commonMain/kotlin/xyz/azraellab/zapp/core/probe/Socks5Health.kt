package xyz.azraellab.zapp.core.probe

/**
 * Готовность SOCKS5-релея по протоколю, а не по открытому порту.
 *
 * Порт открыт -- это ещё не значит, что сервер отвечает: слушать умеет
 * что угодно, а здоровье -- свойство протокольного рукопожатия. Релей
 * готов, когда на приветствие `[05 01 00]` (версия 5, один метод --
 * без аутентификации) приходит выбор метода `[05 00]`. Ровно этот
 * обмен -- то, что реально случится с первым клиентом, и именно его
 * ждём перед «Работает».
 */

/** Приветствие клиента: версия 5, один метод -- no-auth. */
fun socks5Greeting(): ByteArray = byteArrayOf(0x05, 0x01, 0x00)

/**
 * Сервер выбрал no-auth.
 *
 * Ответ короче двух байт -- сломанная форма (не SOCKS5 или обрыв),
 * и это не готовность, а сбой.
 */
fun socks5SelectedNoAuth(response: ByteArray?): Boolean =
    response != null && response.size >= 2 &&
        response[0] == 0x05.toByte() && response[1] == 0x00.toByte()
