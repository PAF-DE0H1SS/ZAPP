package xyz.azraellab.zapp.core.sleep

/**
 * Наблюдение за сном устройства: экран погас / пробуждение.
 *
 * Android: системные рассылки SCREEN_ON/OFF. Десктоп: событий сна у
 * JVM нет, поэтому пробуждение ловится опросом по отставанию часов
 * (компьютер уснул -- монотонное время отстаёт от запланированного
 * тика), а момент засыпания постфактум: сеть уходит вместе со сном,
 * туннель уже мёртв, наблюдатель лишь снимает состояние по галке.
 *
 * Галки живут в конфиге ([xyz.azraellab.zapp.core.VpnConfig.sleepDisconnect]
 * / [xyz.azraellab.zapp.core.VpnConfig.wakeReconnect]), наблюдатель
 * только сообщает события: одна настройка -- одно место правды.
 */
expect object SleepWatch {

    /** Ставит наблюдатель; повторный вызов заменяет предыдущее. */
    fun start(onSleep: () -> Unit, onWake: () -> Unit)

    /** Снимает наблюдатель; отсутствие наблюдателя -- не ошибка. */
    fun stop()
}
